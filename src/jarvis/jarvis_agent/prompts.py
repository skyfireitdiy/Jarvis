DEFAULT_SUMMARY_PROMPT = """<report>
写一份简洁的任务总结（用中文，平实叙述，不要文言或堆砌格式），让接手者不翻历史也能继续。按需分节、分点列出，语言精炼。

1. **目标与进展**：整体目标与当前做到哪一步；目标若中途变化，点出变化与原因；区分"已完成 / 进行中 / 待办"，别混为一谈。
2. **已验证的成果与改动**：列出关键文件与变更；凡标"已完成"的都要能给出验证证据——代码开发务必写明编译/构建是否通过、测试结果、是否实际运行验证过。做不到的不许标"已完成"。
3. **错误、调试与已知问题**：仍存在的错误（含关键报错/堆栈要点）、被证伪的方案及其失败原因。
4. **未完成与下一步**：未竟事项与待办，注明依赖、风险和建议优先级。
5. **我的约束与偏好**：影响后续执行的代码规范、用户偏好与禁区。

要求：只陈述实际发生与验证过的事实，不编造、不推测；宁可少而准，不要多而虚。
</report>"""


SUMMARY_REQUEST_PROMPT = """<summary_request>
把此前对话压缩成一段"能直接继续干活"的浓缩上下文（用中文，平实叙述，不要文言或堆砌格式）。不必复述过程，但要保住继续决策与继续执行所需的信息。按需分点。

1. **目标与进展**：当前整体/阶段目标与已达状态，明确区分"已验证完成 / 进行中 / 待办"；目标若在中途变化，以最新为准并点明变化。
2. **已验证的关键事实与变更**：改过的文件路径/函数/接口、已通过的编译与测试结论、关键技术决策及理由、记住的可复现信息（关键报错/堆栈/参数）。
3. **用户关键信息**：提炼用户输入的关键信息，不必逐条原样复述。重点保留影响后续执行的内容——中途追加或修改的约束、偏好、纠正与否定意见，以及需求变更的要点——这些是压缩后最容易丢失、也最容易导致跑偏的信息。
4. **当前工作**：压缩发生前正在做的事——正在改的文件/函数、正在验证的假设、刚发出的命令与结果、下一步打算做什么。
5. **未解决的问题**：仍存在的错误与卡点、试过但失败的方法及失败原因、待补的测试/文档/边界。
6. **下一步与约束**：待办与建议优先级、依赖与风险、用户的偏好与禁区。

要求：忠于原对话，不新增事实、不臆测；代码开发内容，"已完成"须对应验证证据（编译/测试/运行），达不到就不要标完成；语言精炼，宁可保留关键细节、删掉寒暄与过程复述。

现在直接输出摘要正文，不要调用任何工具。
</summary_request>
"""


def get_task_analysis_prompt(
    has_memory_tool: bool = False, has_generate_new_tool: bool = False
) -> str:
    """依配置返回任务分析提示词

    参数:
        has_memory_tool: 是否有 memory 工具（工具可用性）
        has_generate_new_tool: 是否有 meta_agent 工具（原 generate_new_tool，自举式工具生成器）
    """
    # 第一步：记忆保存部分
    if not has_memory_tool:
        # 若无 memory 工具，说明无法保存记忆
        memory_step = """第一步：记录值得保存的信息
1. 识别任务中的关键信息与知识点
2. 评估是否有值得保存的项目长期记忆或全局长期记忆
3. 注意：当前环境不支持 memory 工具，无法保存记忆。请直接说明识别到的关键信息即可。"""
    else:
        # 有 memory 工具
        memory_step = """第一步：记录值得保存的信息
1. 识别任务中的关键信息与知识点
2. 评估是否有值得保存的项目长期记忆或全局长期记忆
3. 若有价值，用 memory 工具（action=save）保存有价值的信息：
   - project_long_term: 保存与当前项目相关的长期信息（如项目配置、架构决策、开发规范等）
   - global_long_term: 保存通用信息、用户偏好、知识或方法（如技术知识、最佳实践、用户习惯等）"""

    # 第二步：规则体系分析部分
    rule_analysis_step = """第二步：分析规则体系
1. 检查当前项目的全局或项目规则（.jarvis/rules/ 目录，不包括 builtin/rules/ 内置规则）是否有需要完善之处
2. 重点关注以下方面的规则覆盖：
   - 项目级规范（如代码风格、模块设计约定）
   - CI/CD 相关规则
   - 文档规范
   - 性能基准规则
   - 安全检查流程规范
   - 其他项目特定的规范或流程
3. 若发现规则缺失或需要完善：
   - 用 load_rule 工具加载 builtin:rule 查看现有规则体系
   - 评估缺失的规则是否需要新建
   - 若需要新建规则，在第三步中说明
4. 若现有规则已经完善，直接说明即可"""

    # 第三步：工具/方法论分析部分
    if has_generate_new_tool:
        solution_step = """第三步：分析任务解决方案
1. 检查现有工具或方法论是否已能完成该任务，若可以，直接说明即可，无需生成新内容
2. 若现有工具/方法论不足，评估当前任务是否可以通过编写新工具来自动化解决
3. 若可以通过工具解决，请用 meta_agent 工具创建或改进工具：
   - 用 meta_agent 工具，传入 tool_name 与 function_description 参数
   - 工具将借助 CodeAgent/Agent 智能分析需求，自动生成或改进具备自举与自进化能力的完整工具代码
   - 生成/改进后的工具将自动集成到 Jarvis 生态系统，支持编排 Agent 与 CodeAgent 处理复杂任务
4. 若无法通过编写通用工具完成，评估当前的执行流程是否可以总结为通用方法论
5. 若以上都不可行，给出详细理由"""
    else:
        solution_step = """第三步：分析任务解决方案
1. 检查现有工具或方法论是否已能完成该任务，若可以，直接说明即可，无需生成新内容
2. 若现有工具/方法论不足，评估当前任务是否可以通过编写新工具来自动化解决
3. 若可以通过工具解决，请优先用 meta_agent 工具创建/改进新工具（若环境支持），否则手动提供工具代码
4. 若无法通过编写通用工具完成，评估当前的执行流程是否可以总结为通用方法论
5. 若以上都不可行，给出详细理由"""

    # 输出要求部分
    if has_generate_new_tool:
        output_requirements = """<output_requirements>
根据分析结果，输出以下三种情况之一：
1. 若现有工具/方法论可解决，直接输出说明：
已有工具/方法论可解决该问题，无需创建新内容。
可用的工具/方法论：[列出工具名或方法论名]
用法：[简要说明如何使用]
2. 创建工具（若需要新建工具）:
```json
{
  "want": "创建新工具以解决XXX问题",
  "name": "meta_agent",
  "arguments": {
    "tool_name": "工具名",
    "function_description": "工具的详细功能描述，说明工具要解决的具体问题与预期行为"
  }
}
```

3. 创建方法论（若需要新建方法论）:
判断标准：
- 若方法论特定于当前项目（如项目特定的技术方案、开发流程、规范等），用 scope="project"
- 若方法论适用于任何项目（如通用流程、最佳实践、解决方案等），用 scope="global" 或省略该参数（默认为global）

```json
{
  "want": "添加/更新xxxx的方法论",
  "name": "methodology",
  "arguments": {
    "operation": "add/update",
    "problem_type": "方法论类型，不要过细，也不要过泛",
    "scope": "可选值：'project' 或 'global'（默认）。'project' 存至项目目录（.jarvis/methodologies/），适用于项目特定的方法论；'global' 存为全局方法论（用户数据目录），适用于任何项目的通用方法论",
    "content": "方法论内容（支持普通字符串格式）"
  }
}
```

若以上三种情况都不适用，则直接输出理由分析，不要使用工具调用格式。
</output_requirements>"""
    else:
        output_requirements = """<output_requirements>
根据分析结果，输出以下三种情况之一：
1. 若现有工具/方法论可解决，直接输出说明：
已有工具/方法论可解决该问题，无需创建新内容。
可用的工具/方法论：[列出工具名或方法论名]
用法：[简要说明如何使用]
2. 创建工具（若需要新建工具）:
注：若环境支持，请用 meta_agent 工具创建/改进新工具；若不支持，请提供完整的工具代码与说明，我需要手动创建工具文件。
3. 创建方法论（若需要新建方法论）:
判断标准：
- 若方法论特定于当前项目（如项目特定的技术方案、开发流程、规范等），用 scope="project"
- 若方法论适用于任何项目（如通用流程、最佳实践、解决方案等），用 scope="global" 或省略该参数（默认为global）

```json
{
  "want": "添加/更新xxxx的方法论",
  "name": "methodology",
  "arguments": {
    "operation": "add/update",
    "problem_type": "方法论类型，不要过细，也不要过泛",
    "scope": "可选值：'project' 或 'global'（默认）。'project' 存至项目目录（.jarvis/methodologies/），适用于项目特定的方法论；'global' 存为全局方法论（用户数据目录），适用于任何项目的通用方法论",
    "content": "方法论内容（支持普通字符串格式）"
  }
}
```

若以上三种情况都不适用，则直接输出理由分析，不要使用工具调用格式。
</output_requirements>"""

    return f"""<task_analysis>
<request>
当前任务已结束，请按以下步骤分析该任务：

{memory_step}

{rule_analysis_step}

{solution_step}

请根据分析结果采取相应行动。

重要提示：每次只能执行一个操作！
- 若有记忆需要保存，可调用一次 memory 工具（action=save）批量保存多条记忆
- 保存完所有记忆后，再进行工具/方法论的创建或说明
- 不要在一次响应中同时调用多个工具（如同保存记忆与创建工具/方法论）
</request>
<evaluation_criteria>

现有资源评估: 检查现有工具/方法论/组合使用是否能解决问题
工具评估: 通用性、自动化、可靠性、简单性
方法论评估: 提炼通用可重复流程，纳入我的反馈，面向未来复用
<tool_requirements>
工具代码要求:
1. 工具类名与工具名一致，包含name、description、parameters属性，实现execute方法
2. 参数定义遵循JSON Schema，工具调用用Jsonnet格式（支持尾随逗号）
3. 用print展示执行过程，返回{{success, stdout, stderr}}结构化结果
4. 妥善处理异常，失败时清理资源。若需要调用大模型，创建独立实例以免干扰主流程
</tool_requirements>
<methodology_requirements>
方法论格式要求（必须与rule格式对齐）：

方法论内容必须遵循以下结构，与rule文件格式保持一致：

```markdown
# [方法论标题]

## 规则简介

（可选）简要说明方法论的用途、适用场景与预期效果

## 你必须遵守的原则

（必需）方法论的核心原则

### 原则1名称

**要求说明：**

- **必须**：具体要求
- **禁止**：禁止事项

### 原则2名称

**要求说明：**

- **必须**：具体要求
- **禁止**：禁止事项

## 你必须执行的操作

（必需）具体的执行步骤或流程

### 阶段1：阶段名称

1. **步骤1**：具体操作说明
2. **步骤2**：具体操作说明

### 阶段2：阶段名称

1. **步骤1**：具体操作说明
2. **步骤2**：具体操作说明

## 实践指导

（可选）最佳实践建议、常见错误、注意事项等

## 检查清单

（可选）完成后的验证项

- [ ] 检查项1
- [ ] 检查项2
```

**格式对齐要求：**

- **必须**：用与rule文件相同的Markdown结构
- **必须**：包含"你必须遵守的原则"章节
- **必须**：包含"你必须执行的操作"章节
- **必须**：用相同的格式标记（**必须**、**禁止**等）
- **必须**：用相同的章节层级（##、###）
- **建议**：包含"规则简介"、"实践指导"、"检查清单"等可选章节
- **禁止**：用与rule格式不一致的结构（如"问题重述"、"可选步骤"等独立章节）
</methodology_requirements>
{output_requirements}
</task_analysis>"""


# 为向后兼容，保留原常量（用默认参数，假设有 memory 工具）
TASK_ANALYSIS_PROMPT = get_task_analysis_prompt(has_memory_tool=True)
